const bannersPublicitarios = [
    '<i class="fa-brands fa-tiktok"></i> MANG369: ¡Selección de Música para ti!',
    "📢 RTVO: Conecta a través de la música!",
    "🎧 RTVO: Sintoniza las listas de música en directo",
    "🔥 Síguenos en nuestras redes sociales",
    '<i class="fa-brands fa-discord"></i> Únete a la comunidad MANG369 en Discord.'
];

let player;
let isPlaying = false;
let currentCategory = "AMOR";
let currentSongIndex = 0;
let bannerIndex = 0;

function onYouTubeIframeAPIReady() {
    player = new YT.Player('hidden-player', {
        height: '1',
        width: '1',
        playerVars: {
            'controls': 0,
            'rel': 0,
            'modestbranding': 1,
            'iv_load_policy': 3,
            'playsinline': 1,
            'enablejsapi': 1
        },
        events: {
            'onReady': onPlayerReady,
            'onStateChange': onPlayerStateChange,
            'onError': onPlayerError
        }
    });
}

function onPlayerReady(event) {
    renderPlaylist();
    updateSongInfo();
    startBannerRotation();
    
    const firstSong = playlistCategorias[currentCategory][0];
    if (player && typeof player.cueVideoById === 'function') {
        player.cueVideoById(firstSong.id);
    }
}

function onPlayerStateChange(event) {
    if (event.data === YT.PlayerState.PLAYING) {
        isPlaying = true;
        updateUIState();
    } else if (event.data === YT.PlayerState.PAUSED) {
        isPlaying = false;
        updateUIState();
    } else if (event.data === YT.PlayerState.ENDED) {
        nextSong();
    }
}

function onPlayerError(event) {
    console.warn("YouTube Player Error:", event.data, "- Saltando canción.");
    nextSong();
}

function changeCategory() {
    const select = document.getElementById("categorySelect");
    if (!select) return;
    currentCategory = select.value;
    currentSongIndex = 0;
    renderPlaylist();
    loadSong(0);
}

function renderPlaylist() {
    const playlistEl = document.getElementById("playlist");
    if (!playlistEl) return;
    playlistEl.innerHTML = "";
    
    playlistCategorias[currentCategory].forEach((song, index) => {
        const li = document.createElement("li");
        li.textContent = `${index + 1}. ${song.title}`;
        if (index === currentSongIndex) li.classList.add("active");
        li.onclick = () => loadSong(index);
        playlistEl.appendChild(li);
    });
}

function updateSongInfo() {
    const titleEl = document.getElementById("songTitle");
    const artistEl = document.getElementById("songArtist");
    const song = playlistCategorias[currentCategory][currentSongIndex];

    if (titleEl) titleEl.textContent = song ? song.title : "Título no disponible";
    if (artistEl) artistEl.textContent = `Categoría: ${currentCategory.replace('_', ' ')}`;
    
    const items = document.querySelectorAll("#playlist li");
    items.forEach((item, i) => {
        item.classList.toggle("active", i === currentSongIndex);
    });
}

function loadSong(index) {
    currentSongIndex = index;
    const song = playlistCategorias[currentCategory][index];
    if (!song) return;

    if (player && typeof player.loadVideoById === 'function') {
        player.loadVideoById(song.id);
        isPlaying = true;
        updateUIState();
    }
    updateSongInfo();
}

function togglePlay() {
    if (!player) return;
    
    if (isPlaying) {
        if (typeof player.pauseVideo === 'function') player.pauseVideo();
    } else {
        const song = playlistCategorias[currentCategory][currentSongIndex];
        const videoData = (typeof player.getVideoData === 'function') ? player.getVideoData() : null;
        
        if (!videoData || !videoData.video_id) {
            if (typeof player.loadVideoById === 'function') player.loadVideoById(song.id);
        } else {
            if (typeof player.playVideo === 'function') player.playVideo();
        }
    }
}

function updateUIState() {
    const playBtn = document.getElementById("playBtn");
    const visualizer = document.getElementById("visualizer");
    
    if (playBtn) {
        playBtn.innerHTML = isPlaying 
            ? '<i class="fa-solid fa-pause"></i>' 
            : '<i class="fa-solid fa-play"></i>';
    }
    
    if (visualizer) {
        visualizer.classList.toggle("playing", isPlaying);
    }
}

function prevSong() {
    currentSongIndex--;
    if (currentSongIndex < 0) {
        currentSongIndex = playlistCategorias[currentCategory].length - 1;
    }
    loadSong(currentSongIndex);
}

function nextSong() {
    currentSongIndex++;
    if (currentSongIndex >= playlistCategorias[currentCategory].length) {
        currentSongIndex = 0;
    }
    loadSong(currentSongIndex);
}

function startBannerRotation() {
    const adBanner = document.getElementById("adBanner");
    if (!adBanner) return;

    adBanner.innerHTML = bannersPublicitarios[0];

    setInterval(() => {
        bannerIndex = (bannerIndex + 1) % bannersPublicitarios.length;
        adBanner.style.opacity = '0';
        setTimeout(() => {
            adBanner.innerHTML = bannersPublicitarios[bannerIndex];
            adBanner.style.opacity = '1';
        }, 500);
    }, 15000);
}
